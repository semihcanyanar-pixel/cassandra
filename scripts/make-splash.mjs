// Regenerates the splash markup/CSS inside index.html and src/components/Splash.jsx.
// Run: node scripts/make-splash.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const letters = (text, offset) => [...text].map((ch, i) => (ch === ' '
  ? '<i class="sp"></i>'
  : `<i style="--i:${i + offset};--r:${((i * 37) % 50) - 25}deg">${ch}</i>`)).join('');

const markup = (cls = 'class') => `<div ${cls}="splash" role="status" aria-label="Yükleniyor">
      <img src="./icon-192.png" alt="" width="92" height="92">
      <div ${cls}="brand">
        <div ${cls}="t1" aria-hidden="true">${letters('CASSANDRA', 0)}</div>
        <div ${cls}="t2" aria-hidden="true">${letters('FAMILY ASSISTANT', 9)}</div>
      </div>
      <div ${cls}="bar"><i></i></div>
    </div>`;

const css = `    html[data-theme='yorunge'] body { background: #0B0F1A; }
    html[data-theme='teknik'] body { background: #FAFAFA; }
    html[data-theme='mozaik'] body { background: #E8ECF3; }
    /* Splash: same teal-to-deep-blue gradient as the app icon. Letters blink, then fall one by one, then the cycle repeats. */
    .splash { position: fixed; inset: 0; z-index: 50; overflow: hidden; display: flex; flex-direction: column; align-items: center; justify-content: center; gap: 30px;
      background: linear-gradient(180deg, #0c97a6 0%, #00708a 48%, #052f45 100%); font-family: 'Archivo', system-ui, sans-serif; }
    .splash img { width: 92px; height: 92px; border-radius: 23px; box-shadow: 0 12px 36px rgba(0,0,0,.35); animation: splash-pulse 2.4s ease-in-out infinite; }
    .splash .brand { text-align: center; }
    .splash .t1 { font-size: 34px; font-weight: 800; letter-spacing: 5px; color: #f6ead3; text-shadow: 0 2px 12px rgba(0,0,0,.25); }
    .splash .t2 { margin-top: 6px; font-size: 13px; font-weight: 700; letter-spacing: 4px; color: #d9a06f; }
    .splash .t1, .splash .t2 { animation: splash-blink 3s linear infinite; white-space: nowrap; }
    .splash .brand i { display: inline-block; font-style: normal; animation: splash-drop 3s ease-in infinite; animation-delay: calc(var(--i) * 70ms); }
    .splash .brand i.sp { width: .5em; }
    .splash .bar { width: 120px; height: 4px; border-radius: 2px; overflow: hidden; background: rgba(246,234,211,.22); position: relative; margin-top: 6px; }
    .splash .bar i { position: absolute; top: 0; bottom: 0; width: 40%; border-radius: 2px; background: #f6ead3; animation: splash-bar 1.2s ease-in-out infinite; }
    @keyframes splash-blink { 0% { opacity: 0; } 8% { opacity: 1; } 15% { opacity: .15; } 22% { opacity: 1; } 29% { opacity: .15; } 36%, 100% { opacity: 1; } }
    @keyframes splash-drop {
      0%, 36% { transform: none; opacity: 1; }
      68% { transform: translateY(70vh) rotate(var(--r)); opacity: 0; }
      69%, 92% { transform: translateY(-26px); opacity: 0; }
      100% { transform: none; opacity: 1; }
    }
    @keyframes splash-pulse { 0%, 100% { transform: scale(.95); } 50% { transform: scale(1); } }
    @keyframes splash-bar { 0% { left: -40%; } 100% { left: 100%; } }
    @media (prefers-reduced-motion: reduce) { .splash img, .splash .t1, .splash .t2, .splash .brand i, .splash .bar i { animation: none; } .splash .bar i { left: 0; width: 100%; opacity: .5; } }`;

// index.html: replace the <style> block and the #app placeholder.
let html = readFileSync('index.html', 'utf8');
html = html.replace(/<style>[\s\S]*?<\/style>/, `<style>\n${css}\n  </style>`);
html = html.replace(/<div id="app">[\s\S]*?<\/div>\s*<script type="module"/, `<div id="app">${markup()}</div>\n  <script type="module"`);
writeFileSync('index.html', html);

// Splash.jsx: same markup via dangerouslySetInnerHTML so the two never drift apart.
const jsx = `// Loading screen: identical markup/styles to the static splash in index.html (generated by scripts/make-splash.mjs),
// so there is no visual jump when the app boots.
const HTML = ${JSON.stringify(markup().replace(/^<div class="splash"[^>]*>|<\/div>$/g, ''))};
export const Splash = () => <div class="splash" role="status" aria-label="Yükleniyor" dangerouslySetInnerHTML={{ __html: HTML }} />;
`;
writeFileSync('src/components/Splash.jsx', jsx);
console.log('splash regenerated');
